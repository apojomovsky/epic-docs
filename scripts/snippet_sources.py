#!/usr/bin/env python3
"""Guide snippet check (design docs/08-docs-overhaul.md section 12).

Every snippet in a guide comes from a tested file: a fenced block in a
guide is either a reader-typed command (bash/console), a diagram, or it
cites its source with a snippet include or a backticked path naming the
file, which must exist in the hub or a sibling checkout. Stdlib only;
exit 1 on violation, 2 on usage error.
"""

import os
import re
import subprocess
import sys

COMMAND_LANGS = frozenset({"bash", "sh", "shell", "console", "mermaid"})
SOURCE_SUFFIXES = frozenset({
    ".c", ".h", ".cpp", ".hpp", ".cc", ".S", ".py", ".sh", ".ini",
    ".toml", ".yaml", ".yml", ".json", ".rs", ".mk",
})
SOURCE_NAMES = frozenset({"Makefile", "makefile"})
FENCE_OPEN_RE = re.compile(r"^(\s*)(```|~~~)(\w*)\s*(.*)$")
FENCE_CLOSE_RE = re.compile(r"^\s*(```|~~~)\s*$")
INCLUDE_RE = re.compile(r'--8<--\s+"([^"]+)"')
CITED_PATH_RE = re.compile(r"`([^`]*?/[^`]*?\.[^`]*?)`")


def hub_root():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def search_roots(root):
    roots = [root]
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--git-common-dir"], capture_output=True,
            text=True, cwd=root, check=True).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return roots
    if not os.path.isabs(out):
        out = os.path.abspath(os.path.join(root, out))
    sib = os.path.dirname(os.path.dirname(out))
    for repo in ("epic-cc", "epic-hal", "epic-platformio", "epic-tools"):
        candidate = os.path.join(sib, repo)
        if os.path.isdir(candidate):
            roots.append(candidate)
    return roots


def find_guides(root):
    found = []
    for top in (os.path.join(root, "docs"),):
        guides = os.path.join(top, "guides")
        if os.path.isdir(guides):
            for base, _, files in os.walk(guides):
                found.extend(os.path.join(base, f) for f in sorted(files)
                             if f.endswith(".md"))
    return sorted(found)


def iter_fences(lines):
    """Yield (start, end, lang) for each block; end is None if unclosed."""
    start = None
    lang = ""
    for idx, line in enumerate(lines):
        if start is None:
            match = FENCE_OPEN_RE.match(line)
            if match:
                start, lang = idx, match.group(3).lower()
        elif FENCE_CLOSE_RE.match(line):
            yield start, idx, lang
            start = None
    if start is not None:
        yield start, None, lang


def citation(lines, start):
    """Source path cited for the block at start, or None."""
    context = [lines[i] for i in range(max(0, start - 4), start)
               if lines[i].strip()]
    for line in context[-3:]:
        match = CITED_PATH_RE.search(line)
        if match:
            return match.group(1)
    return None


def is_generated(lines):
    """True when the page says tooling produced it (design section 7)."""
    return any("generated by" in line.lower() for line in lines[:5]
               if line.strip())


def check_lines(lines, filename, roots):
    """All findings for one guide's lines. Pure; used by tests."""
    findings = []
    if is_generated(lines):
        return findings
    for start, end, lang in iter_fences(lines):
        if end is None:
            findings.append((start + 1, f"[{filename}] unclosed code block"))
            continue
        if not lang:
            findings.append((start + 1, f"[{filename}] untagged code block; "
                             "name its language"))
            continue
        if lang in COMMAND_LANGS:
            continue
        body = "\n".join(lines[start + 1:end])
        match = INCLUDE_RE.search(body)
        cited = match.group(1) if match else citation(lines, start)
        if cited is None:
            findings.append((start + 1, f"[{filename}] snippet names no "
                             "tested source file"))
            continue
        base = cited.rsplit("/", 1)[-1]
        _, dot, suffix = base.rpartition(".")
        if base not in SOURCE_NAMES and not (dot and "." + suffix in
                                             SOURCE_SUFFIXES):
            findings.append((start + 1, f"[{filename}] cited file is not a "
                             f"tested source: '{cited}'"))
            continue
        if not any(os.path.isfile(os.path.join(r, cited)) for r in roots):
            findings.append((start + 1, f"[{filename}] cited source not "
                             f"found: '{cited}'"))
    return findings


def main(argv):
    args = argv[1:]
    if "--help" in args:
        sys.stdout.write(__doc__ + "\nusage: snippet_sources.py [PATH...]\n")
        return 0
    unknown = [a for a in args if a.startswith("-")]
    if unknown:
        sys.stderr.write(f"unknown option: {' '.join(unknown)}\n")
        return 2
    root = hub_root()
    paths = args or find_guides(root)
    roots = search_roots(root)
    failed = False
    for path in paths:
        try:
            with open(path, encoding="utf-8") as handle:
                lines = handle.read().splitlines()
        except OSError as exc:
            print(f"{path}: cannot read: {exc}")
            failed = True
            continue
        for lineno, message in check_lines(lines, path, roots):
            print(f"{path}:{lineno}: {message}")
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
